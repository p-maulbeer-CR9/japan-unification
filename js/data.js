// LAND_ADJACENCY + SEA_ADJACENCY_PAIRS を統合した最終隣接テーブル（双方向・重複無し）を構築する。
function buildAdjacency() {
  const table = {};
  PREFECTURES.forEach((p) => { table[p.id] = new Set(); });

  Object.entries(LAND_ADJACENCY).forEach(([id, neighbors]) => {
    neighbors.forEach((n) => {
      table[id].add(n);
      table[n].add(id);
    });
  });

  SEA_ADJACENCY_PAIRS.forEach(([a, b]) => {
    table[a].add(b);
    table[b].add(a);
  });

  const result = {};
  Object.entries(table).forEach(([id, set]) => { result[id] = Array.from(set); });
  return result;
}

const ADJACENCY = buildAdjacency();

// 海上隣接ペアかどうかの判定（地図描画で点線表示するために使用）
const SEA_LINK_SET = new Set(
  SEA_ADJACENCY_PAIRS.map(([a, b]) => [a, b].sort().join('|'))
);
function isSeaLink(a, b) {
  return SEA_LINK_SET.has([a, b].sort().join('|'));
}

